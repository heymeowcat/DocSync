"""GitHub App authentication and webhook helpers."""

from __future__ import annotations

import hashlib
import hmac
import logging
import os
from typing import Any

import jwt
import requests
from github import Auth, Github

logger = logging.getLogger(__name__)


class GitHubApp:
    def __init__(
        self,
        app_id: str | None = None,
        private_key: str | None = None,
        webhook_secret: str | None = None,
    ):
        self.app_id = app_id or os.environ.get("GITHUB_APP_ID", "")
        self.private_key = (private_key or os.environ.get("GITHUB_PRIVATE_KEY", "")).replace("\\n", "\n")
        self.webhook_secret = webhook_secret or os.environ.get("GITHUB_WEBHOOK_SECRET", "")

    def is_configured(self) -> bool:
        return bool(self.app_id and self.private_key)

    def app_jwt(self) -> str:
        import time

        now = int(time.time())
        payload = {"iat": now - 60, "exp": now + 600, "iss": self.app_id}
        return jwt.encode(payload, self.private_key, algorithm="RS256")

    def installation_token(self, installation_id: int) -> str:
        headers = {"Authorization": f"Bearer {self.app_jwt()}", "Accept": "application/vnd.github+json"}
        url = f"https://api.github.com/app/installations/{installation_id}/access_tokens"
        r = requests.post(url, headers=headers, timeout=30)
        r.raise_for_status()
        return r.json()["token"]

    def client_for_installation(self, installation_id: int) -> Github:
        token = self.installation_token(installation_id)
        return Github(auth=Auth.Token(token))

    @staticmethod
    def verify_signature(secret: str, body: bytes, signature: str) -> bool:
        if not secret or not signature:
            return False
        expected = "sha256=" + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()
        return hmac.compare_digest(expected, signature)

    def create_check_run(self, repo, head_sha: str, name: str, conclusion: str, summary: str) -> None:
        try:
            repo.create_check_run(
                name=name,
                head_sha=head_sha,
                status="completed",
                conclusion=conclusion,
                output={"title": name, "summary": summary[:65000]},
            )
        except Exception as exc:  # noqa: BLE001
            logger.warning("Could not create check run: %s", exc)

    def handle_event(self, event: str, payload: dict[str, Any]) -> dict[str, Any]:
        if event == "pull_request" and payload.get("action") in {"opened", "synchronize", "reopened"}:
            return {"status": "queued", "pr": payload["pull_request"]["number"]}
        return {"status": "ignored", "event": event}


def create_fix_pr(
    gh_app: GitHubApp,
    repo,
    base: str,
    head_sha: str,
    pr_number: int,
    affected: dict,
    diff: str,
    llm,
    cfg,
) -> str | None:
    """Create a draft PR with LLM-regenerated documentation. Returns PR URL or None."""
    if not getattr(cfg, "auto_fix", False):
        return None
    branch = f"docsync/fix-pr-{pr_number}"
    try:
        base_ref = repo.get_branch(base)
        try:
            repo.create_git_ref(ref=f"refs/heads/{branch}", sha=base_ref.commit.sha)
        except Exception:  # noqa: BLE001
            pass
        for _src, docs in list(affected.items())[:5]:
            for d in docs:
                try:
                    f = repo.get_contents(d, ref=head_sha)
                    old = base64_decode(f.content) if hasattr(f, "content") else ""
                except Exception:  # noqa: BLE001
                    continue
                new_content = _regenerate_doc(llm, cfg, d, old, diff)
                if not new_content or new_content == old:
                    continue
                try:
                    repo.update_file(
                        path=d,
                        message=f"docs: update {d} (docsync auto-fix)",
                        content=new_content,
                        sha=f.sha,
                        branch=branch,
                    )
                except Exception:  # noqa: BLE001
                    continue
        pr = repo.create_pull(
            title=f"docs: DocSync auto-fix for PR #{pr_number}",
            body="Automated documentation updates generated by DocSync. Review before merging.",
            head=branch,
            base=base,
            draft=True,
        )
        return pr.html_url
    except Exception as exc:  # noqa: BLE001
        logger.warning("Auto-fix PR creation failed: %s", exc)
        return None


def _regenerate_doc(llm, cfg, path: str, old: str, diff: str) -> str:
    if llm is None:
        return old
    prompt = (
        f"Update the following documentation file to reflect the code changes.\n"
        f"File: {path}\n\nCurrent content:\n{old[:8000]}\n\nDiff:\n```diff\n{diff[:8000]}\n```\n\n"
        "Return only the updated full document in Markdown."
    )
    try:
        resp = llm.chat.completions.create(model=cfg.model, messages=[{"role": "user", "content": prompt}])
        return resp.choices[0].message.content.strip()
    except Exception:  # noqa: BLE001
        return old


def base64_decode(content: str) -> str:
    import base64

    try:
        return base64.b64decode(content).decode("utf-8", errors="ignore")
    except Exception:  # noqa: BLE001
        return ""
